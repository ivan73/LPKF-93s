"""LPKF LMD 3.0 (CircuitCAM 4.x / BoardMaster 5.x) – Lesen und Schreiben.

Aufbau (reverse-engineered aus CircuitCAM 4.0 Export):
  ASCII-Kopf, Zeilen mit b'\\n\\r' getrennt, abgeschlossen mit 0x1A
  Opcode-Größentabelle: 0x0B <op> <int32 bytes>  (Reihenfolge wie CircuitCAM)
  Phasen: 0x82 0x81  0x07 <Phase>\\0  0x07 <Layer>\\0  0x00
     Werkzeuge: 0x80 0x03 <int32 nr> 0x01 <byte typ 0=Fräsen 1=Bohren> 0x05 <float32 Ø m> 0x07 <Name>\\0 0x00
     Befehle (alle Koordinaten float32 in Metern):
        0x10 <int32>              Werkzeug wählen
        0x0C x y                  Absenken/Start (Pen-Up-Move zu x,y)
        0x0D x y                  Linie nach x,y
        0x11 x y cx cy r          Bogen nach x,y um cx,cy; r<0 = im Uhrzeigersinn
        0x0F x y                  Bohrung
        (0x0E 12 Byte – deklariert, im Beispiel ungenutzt)
     0x00 Phasenende
"""
import struct

SIZES = [(0x0c, 8), (0x0d, 8), (0x0e, 12), (0x0f, 8), (0x10, 4), (0x11, 20), (0x11, 20)]

def read(data):
    i = data.index(b'\x1a') + 1
    header = data[:i - 1].decode('latin1')
    sizes = {}
    while data[i] == 0x0b:
        op = data[i + 1]; sizes.setdefault(op, struct.unpack_from('<i', data, i + 2)[0]); i += 6
    phases = []
    def rstr():
        nonlocal i
        assert data[i] == 7, hex(i)
        j = data.index(b'\0', i + 1); s = data[i + 1:j].decode('latin1'); i = j + 1; return s
    while i < len(data):
        assert data[i:i + 2] == b'\x82\x81', hex(i)
        i += 2
        ph = rstr(); ly = rstr(); assert data[i] == 0; i += 1
        tools = []
        while data[i] == 0x80:
            i += 1; nr = struct.unpack_from('<i', data, i + 1)[0]; i += 5
            typ = data[i + 1]; i += 2
            dia = struct.unpack_from('<f', data, i + 1)[0]; i += 5
            name = rstr(); assert data[i] == 0; i += 1
            tools.append((nr, typ, dia, name))
        cmds = []
        while data[i] != 0:
            op = data[i]
            if op == 0x10:
                cmds.append((op, struct.unpack_from('<i', data, i + 1)[0])); i += 5; continue
            n = sizes[op]; cmds.append((op, struct.unpack_from('<%df' % (n // 4), data, i + 1))); i += 1 + n
        i += 1
        phases.append(dict(phase=ph, layer=ly, tools=tools, cmds=cmds))
    return header, phases

def write(header, phases):
    out = bytearray(header.encode('latin1')); out += b'\x1a'
    for op, n in SIZES: out += bytes([0x0b, op]) + struct.pack('<i', n)
    for p in phases:
        out += b'\x82\x81\x07' + p['phase'].encode('latin1') + b'\0\x07' + p['layer'].encode('latin1') + b'\0\0'
        for nr, typ, dia, name in p['tools']:
            out += b'\x80\x03' + struct.pack('<i', nr) + bytes([1, typ, 5]) + struct.pack('<f', dia)
            out += b'\x07' + name.encode('latin1') + b'\0\0'
        for op, a in p['cmds']:
            if op == 0x10: out += b'\x10' + struct.pack('<i', a)
            else: out += bytes([op]) + struct.pack('<%df' % len(a), *a)
        out += b'\0'
    return bytes(out)

def make_header(user='LBS-Meran'):
    lines = ['LPKF_Mill_Drill File (LMD) Version 3.0',
             'Generated by: CircuitCAM Version 4.0 (414c), S/N: 999999P22',
             'User: ' + user, 'Organization: ', 'Location: ']
    return ''.join(l + '\n\r' for l in lines)
